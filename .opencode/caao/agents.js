/**
 * CAAO — agent synthesis.
 *
 * Capability + provider binding -> one disposable opencode subagent.
 * The YAML files remain the single source of truth: these markdown files are
 * generated artifacts and `npm run caao:sync` regenerates them.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"

import { CAAO_HOME, allCapabilities } from "./config.js"
import { agentName, poolsFor, resolveProvider } from "./provider.js"

export const AGENT_DIR = join(CAAO_HOME, "agent")

export const ORCHESTRATION_TOOLS = [
  "caao_context",
  "caao_triage",
  "caao_plan",
  "caao_next",
  "caao_expand",
  "caao_record",
  "caao_merge",
  "caao_status",
  "caao_report",
  "caao_registry",
  "caao_doctor",
]

const GENERATED_MARKER = "<!-- generated by caao:sync — edit capabilities.yaml / providers.yaml instead -->"

function frontmatter(fields) {
  const lines = ["---"]
  for (const [key, value] of Object.entries(fields)) {
    if (value === undefined) continue
    if (value && typeof value === "object") {
      lines.push(`${key}:`)
      for (const [k, v] of Object.entries(value)) lines.push(`  ${k}: ${v}`)
    } else if (typeof value === "string" && /[:#]/.test(value)) {
      lines.push(`${key}: ${JSON.stringify(value)}`)
    } else {
      lines.push(`${key}: ${value}`)
    }
  }
  lines.push("---")
  return lines.join("\n")
}

function workerTools(capability) {
  const tools = Object.fromEntries(ORCHESTRATION_TOOLS.map((name) => [name, false]))
  tools.task = false
  tools.write = Boolean(capability.mutates)
  tools.edit = Boolean(capability.mutates)
  tools.patch = Boolean(capability.mutates)
  return tools
}

export function renderWorker(config, capability, poolId = null) {
  const defaultProvider = resolveProvider(config, capability.id)
  const pool = poolId ?? defaultProvider.pool
  const definition = config.providers.pools[pool]
  const name = agentName(capability.id, pool, defaultProvider.pool)
  const body = [
    GENERATED_MARKER,
    "",
    `You are a disposable CAAO worker executing the **${capability.title}** capability.`,
    "",
    `Capability intent: ${capability.intent}`,
    `Objective: ${capability.worker?.objective ?? capability.intent}`,
    "",
    "## Rules",
    ...(capability.worker?.checklist ?? []).map((item) => `- ${item}`),
    "- You never coordinate with other workers. All coordination goes through the Execution Manager.",
    "- You act only inside the scope handed to you. Anything outside it is not your problem.",
    "- If the scope is insufficient, say so and lower your confidence instead of guessing.",
    capability.mutates ? "- You may modify files inside your scope." : "- You are read-only. Report findings, never edit files.",
    "",
    "## Output",
    `Return: ${capability.worker?.output_contract ?? "summary, confidence"}`,
    "",
    "End your reply with a single final line:",
    "",
    "```",
    "CONFIDENCE: <0.00-1.00>",
    "```",
  ].join("\n")

  return {
    file: `${name}.md`,
    content: `${frontmatter({
      description: `${capability.title} — ${capability.intent}`,
      mode: "subagent",
      model: definition.model,
      temperature: definition.temperature,
      tools: workerTools(capability),
    })}\n\n${body}\n`,
  }
}

export function renderExecutionManager(config, { name, description }) {
  const provider = resolveProvider(config, "planning")
  const prompt = readFileSync(join(CAAO_HOME, "prompts", "execution-manager.md"), "utf8").trim()

  return {
    file: `${name}.md`,
    content: `${frontmatter({
      description,
      mode: "primary",
      model: provider.model,
      temperature: 0.1,
      tools: { write: false, edit: false, patch: false },
    })}\n\n${GENERATED_MARKER}\n\n${prompt}\n`,
  }
}

export function renderAgents(config) {
  const workers = allCapabilities(config).flatMap((capability) =>
    poolsFor(config, capability.id).map((pool) => renderWorker(config, capability, pool)),
  )
  return [
    ...workers,
    renderExecutionManager(config, { name: "caao", description: "CAAO Execution Manager — the single entry point" }),
    renderExecutionManager(config, { name: "build", description: "CAAO Execution Manager (default entry point)" }),
  ]
}

export function syncAgents(config) {
  const rendered = renderAgents(config)
  if (!existsSync(AGENT_DIR)) mkdirSync(AGENT_DIR, { recursive: true })

  const expected = new Set(rendered.map((agent) => agent.file))
  for (const file of readdirSync(AGENT_DIR)) {
    if (file.endsWith(".md") && !expected.has(file) && readFileSync(join(AGENT_DIR, file), "utf8").includes(GENERATED_MARKER)) {
      rmSync(join(AGENT_DIR, file))
    }
  }

  const written = []
  for (const agent of rendered) {
    const path = join(AGENT_DIR, agent.file)
    const current = existsSync(path) ? readFileSync(path, "utf8") : null
    if (current !== agent.content) {
      writeFileSync(path, agent.content, "utf8")
      written.push(agent.file)
    }
  }
  return { total: rendered.length, written }
}

export function detectDrift(config) {
  return renderAgents(config).filter((agent) => {
    const path = join(AGENT_DIR, agent.file)
    return !existsSync(path) || readFileSync(path, "utf8") !== agent.content
  })
}
